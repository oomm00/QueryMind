/**
 * generateRun — asking for N questions when the backend hands back one.
 *
 * POST /questions/generate returns a single question and ignores a count, so a
 * request for ten is ten calls. They are made at most two at a time: enough to
 * keep the model busy, few enough that a rate limit is not provoked.
 *
 * Each call is asked for the next Bloom level in turn, round-robin over the
 * chips the student kept, so a run is mixed rather than one level on end.
 *
 * Three failures are worth another go rather than a shrug:
 *
 *   DUPLICATE_QUESTION         ask again at a different Bloom, twice, then skip
 *   BLOOM_ALIGNMENT_MISMATCH   ask the same level once more, then skip
 *   RATE_LIMIT_EXCEEDED        wait out Retry-After, then resume
 *
 * NO_CONTEXT is different in kind: it means the material does not cover the
 * topic, so the whole run stops and the page offers the closest topic it does
 * know. Everything else stops the run with a sentence from
 * api/errorMessages.js - never a code.
 *
 * Losing a call is not losing the run: whatever arrived is kept, and the page
 * offers to start with fewer questions rather than throwing the work away.
 *
 * No React, no storage and no fetch of its own: the call is injected, so the
 * whole rule can be exercised with a fake one.
 */

import { customConceptId, MAX_IN_FLIGHT } from './generateForm.js'
import { generationErrorCode } from '../api/errorMessages.js'

/** How many questions a run asks the server for at once. */
export { MAX_IN_FLIGHT }

/** One call may think for this long before it is counted as lost. */
export const PER_CALL_TIMEOUT_MS = 50_000

/** How long a run may sit out a rate limit when no Retry-After arrived. */
export const RATE_LIMIT_WAIT_MS = 2_000

/** What a question generated by the server says its source is. */
export const GENERATED_ORIGIN_LABEL = 'Generated'

/** The idle note under the progress line, so 30 seconds is not a mystery. */
export const ANALYZE_HINT = 'Analyze questions can take up to 30 seconds.'

/** The codes this module treats as "ask again" rather than "stop". */
export const DUPLICATE_QUESTION = 'DUPLICATE_QUESTION'
export const BLOOM_ALIGNMENT_MISMATCH = 'BLOOM_ALIGNMENT_MISMATCH'
export const RATE_LIMIT_EXCEEDED = 'RATE_LIMIT_EXCEEDED'
export const NO_CONTEXT = 'NO_CONTEXT'

/** How many times a duplicate question is asked at another Bloom before it is dropped. */
export const DUPLICATE_ATTEMPTS = 2

/** How many times one slot will sit out a rate limit before it gives up. */
export const RATE_LIMIT_ATTEMPTS = 2

/**
 * A score as a share of one. The backend grades on its own scale; this is the
 * one place that scale is narrowed to the 0..1 the session and the mastery
 * store both speak.
 */
export function normaliseScore(value) {
  // A score that never arrived is not a score of zero: an unmarked answer must
  // read as unscored, not as wrong.
  if (value === null || value === undefined || value === '') return null
  const number = Number(value)
  if (!Number.isFinite(number)) return null
  if (number > 1) return Math.min(1, Math.max(0, number / 100))
  return Math.min(1, Math.max(0, number))
}

/** The seconds a Retry-After said to wait, in milliseconds, or the fallback. */
export function retryAfterMs(error) {
  const raw =
    error?.retryAfter ??
    error?.data?.retry_after ??
    error?.data?.retryAfter ??
    error?.headers?.get?.('Retry-After')
  const seconds = Number(raw)
  if (!Number.isFinite(seconds) || seconds <= 0) return RATE_LIMIT_WAIT_MS
  return Math.min(seconds * 1000, 30_000)
}

function sleep(ms, signal) {
  return new Promise((resolve) => {
    if (signal?.aborted) {
      resolve()
      return
    }
    const timer = setTimeout(finish, ms)
    function finish() {
      clearTimeout(timer)
      signal?.removeEventListener?.('abort', finish)
      resolve()
    }
    signal?.addEventListener?.('abort', finish, { once: true })
  })
}

/**
 * One generated question in the shape the session, the question page and the
 * results page already speak - the same shape content questions take, plus the
 * source that tells the two apart.
 *
 * The backend may not hand back an id (the adapter refuses to invent one), so
 * the caller passes a `fallbackId`: a key for this browser's own session list,
 * never a claim about a server-side row.
 */
export function generatedToSessionQuestion(raw, meta = {}) {
  const options = Array.isArray(raw?.options) ? raw.options : []
  const answer = raw?.correct_answer

  let correctIndex = Number.isInteger(raw?.correctIndex) ? raw.correctIndex : undefined
  if (correctIndex === undefined && options.length > 0 && typeof answer === 'string') {
    const found = options.findIndex(
      (option) => String(option).trim().toLowerCase() === answer.trim().toLowerCase()
    )
    if (found >= 0) correctIndex = found
  }

  const type = options.length > 0 && correctIndex !== undefined ? 'mcq' : 'short'

  return {
    question_id: raw?.question_id ?? meta.fallbackId,
    question_text: raw?.question_text ?? '',
    type,
    bloom_level: raw?.bloom_level ?? meta.bloom ?? 'understand',
    difficulty: raw?.difficulty ?? meta.difficulty ?? 'medium',
    options,
    correctIndex,
    answerKey: typeof answer === 'string' ? answer : '',
    rubric: Array.isArray(raw?.rubric) ? raw.rubric : [],
    explanation: raw?.explanation ?? '',
    needsHumanCheck: type !== 'mcq',
    topic: meta.topic ?? raw?.topic ?? '',
    conceptId: meta.conceptId ?? '',
    conceptTitle: meta.topic ?? '',
    topicId: '',
    origin: 'generated',
    originLabel: GENERATED_ORIGIN_LABEL,
    lessonId: null,
    blockIndex: null,
    hints: Array.isArray(raw?.hints) ? raw.hints : [],
    resources: [],
  }
}

/**
 * Ask for `count` questions, at most two calls in flight, reporting as they
 * arrive.
 *
 * @param {object} request
 * @param {(payload: object, options: {signal?: AbortSignal}) => Promise<{questions: Array}>} request.generate
 * @param {string} request.topic - what was typed
 * @param {string} request.subject - the subject the topic matched
 * @param {string} request.difficulty
 * @param {string[]} request.blooms - the chips the student kept, in order
 * @param {number} request.count
 * @param {AbortSignal} [request.signal] - Cancel
 * @param {(progress: object) => void} [request.onProgress]
 * @returns {Promise<{questions: Array, skipped: number, noContext: boolean,
 *                    error: Error|null, cancelled: boolean}>}
 */
export async function runGeneration({
  generate,
  topic,
  subject,
  difficulty = 'medium',
  blooms = [],
  count = 0,
  signal,
  onProgress,
} = {}) {
  const wanted = Math.max(0, Number(count) || 0)
  const levels = blooms.length > 0 ? [...blooms] : ['understand']
  const conceptId = customConceptId(topic) ?? 'custom:topic'

  const questions = []
  let skipped = 0
  let noContext = false
  let error = null
  let cancelled = false
  let started = 0
  let nextBloom = 0

  const stopped = () => cancelled || noContext || Boolean(error) || Boolean(signal?.aborted)
  const report = () => onProgress?.({ ready: questions.length, target: wanted, skipped })

  const takeBloom = () => {
    const level = levels[nextBloom % levels.length]
    nextBloom += 1
    return level
  }

  const keep = (raw, bloom, index) => {
    questions.push(
      generatedToSessionQuestion(raw, {
        topic,
        conceptId,
        fallbackId: `generated:${conceptId}:${index}`,
        bloom,
        difficulty,
      })
    )
  }

  const ask = async (bloom) => {
    const result = await generate(
      { topic, subject, bloom_level: bloom, difficulty, count: 1 },
      { signal }
    )
    return result?.questions?.[0] ?? null
  }

  const oneSlot = async () => {
    while (!stopped() && started < wanted) {
      const index = started
      started += 1
      let bloom = takeBloom()
      let duplicates = 0
      let mismatches = 0
      let rateLimits = 0

      for (;;) {
        if (stopped()) return

        try {
          const raw = await ask(bloom)
          if (stopped()) return
          if (raw) keep(raw, bloom, index)
          else skipped += 1
          report()
          break
        } catch (failure) {
          if (signal?.aborted) {
            cancelled = true
            return
          }

          const code = generationErrorCode(failure)

          if (code === NO_CONTEXT) {
            noContext = true
            return
          }

          if (code === DUPLICATE_QUESTION && duplicates < DUPLICATE_ATTEMPTS) {
            duplicates += 1
            bloom = takeBloom()
            continue
          }

          if (code === BLOOM_ALIGNMENT_MISMATCH && mismatches < 1) {
            mismatches += 1
            continue
          }

          if (code === RATE_LIMIT_EXCEEDED && rateLimits < RATE_LIMIT_ATTEMPTS) {
            rateLimits += 1
            await sleep(retryAfterMs(failure), signal)
            if (stopped()) return
            continue
          }

          if (code === DUPLICATE_QUESTION || code === BLOOM_ALIGNMENT_MISMATCH) {
            skipped += 1
            report()
            break
          }

          error = failure
          return
        }
      }
    }
  }

  if (wanted > 0) {
    const slots = Math.min(MAX_IN_FLIGHT, wanted)
    await Promise.all(Array.from({ length: slots }, () => oneSlot()))
  }

  report()
  return { questions, skipped, noContext, error, cancelled: cancelled || Boolean(signal?.aborted) }
}
